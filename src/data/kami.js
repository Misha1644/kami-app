export function greeting(date = new Date()) {
  const h = date.getHours();
  if (h < 6 || h >= 23) return { text: pick(GREETINGS.night), mood: 'sleepy' };
  if (h < 12) return { text: pick(GREETINGS.morning), mood: 'happy' };
  if (h < 20) return { text: pick(GREETINGS.day), mood: 'happy' };
  return { text: pick(GREETINGS.evening), mood: 'happy' };
}

